/** A catalog icon by name, or the model's single emoji as text. */
export function UiIcon({ name, size = 18 }: { name: string; size?: number }) {
  const Icon = Object.hasOwn(ICONS, name) ? ICONS[name as UiIconName] : null;
  if (Icon) return <Icon size={size} strokeWidth={1.9} aria-hidden />;
  return (
    <span className="dui-emoji" style={{ fontSize: size }} aria-hidden>
      {name}
    </span>
  );
}
