const cubic = (p0, p1, p2, p3, t) => {
  const u = 1 - t;
  return u * u * u * p0 + 3 * u * u * t * p1 + 3 * u * t * t * p2 + t * t * t * p3;
};
/** Position keys along cubic segments [[x0,y0,x1,y1,x2,y2,x3,y3], …] across [from, to]. */
function along(segments, from, to, steps = 8) {
  const xs = [];
  const ys = [];
  const total = segments.length * steps;
  segments.forEach((s, i) => {
    for (let j = i ? 1 : 0; j <= steps; j++) {
      const u = j / steps;
      const t = from + ((i * steps + j) / total) * (to - from);
      xs.push([n(t), n(cubic(s[0], s[2], s[4], s[6], u))]);
      ys.push([n(t), n(cubic(s[1], s[3], s[5], s[7], u))]);
    }
  });
  return [A('x', xs, 'l'), A('y', ys, 'l')];
}

