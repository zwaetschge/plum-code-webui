// Generate Android's contracts from the shared catalog. --check is suitable for CI.
import { UI_COMPONENT_CATALOG } from '../packages/shared/dist/utils/dynamicUiCatalog.js';
import { readFileSync, writeFileSync } from 'node:fs';
const file = new URL(
  '../packages/android/app/src/main/java/com/claudewebui/app/ui/components/dynamicui/DynamicUiCatalog.kt',
  import.meta.url
);
const content = `// Generated by scripts/generate-dynamic-ui-catalog.mjs. Do not edit.\npackage com.claudewebui.app.ui.components.dynamicui\n\nval UI_NODE_TYPES = listOf(${UI_COMPONENT_CATALOG.map((c) => JSON.stringify(c.type)).join(', ')})\n\ninternal val UI_REQUIRED_FIELDS = mapOf(\n${UI_COMPONENT_CATALOG.map((c) => `    ${JSON.stringify(c.type)} to listOf<String>(${c.required.map((v) => JSON.stringify(v)).join(', ')})`).join(',\n')}\n)\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== content)
    throw new Error(
      'Android Dynamic UI catalog is stale; run node scripts/generate-dynamic-ui-catalog.mjs'
    );
} else writeFileSync(file, content);
