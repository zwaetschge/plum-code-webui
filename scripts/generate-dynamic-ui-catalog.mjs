// Generate Android's contracts from the shared catalog. --check is suitable for CI.
import {
  UI_ACTION_TYPES,
  UI_COMPONENT_CATALOG,
  UI_ICON_NAMES,
  UI_LIVE_NODE_TYPES,
} from '../packages/shared/dist/utils/dynamicUiCatalog.js';
import { UI_WEATHER_ICONS } from '../packages/shared/dist/utils/dynamicUiLive.js';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const file = new URL(
  '../packages/android/app/src/main/java/com/claudewebui/app/ui/components/dynamicui/DynamicUiCatalog.kt',
  import.meta.url
);
const list = (values) => values.map((v) => JSON.stringify(v)).join(', ');
const content = `// Generated by scripts/generate-dynamic-ui-catalog.mjs. Do not edit.\npackage com.claudewebui.app.ui.components.dynamicui\n\nval UI_NODE_TYPES = listOf(${list(UI_COMPONENT_CATALOG.map((c) => c.type))})\n\ninternal val UI_REQUIRED_FIELDS = mapOf(\n${UI_COMPONENT_CATALOG.map((c) => `    ${JSON.stringify(c.type)} to listOf<String>(${list(c.required)})`).join(',\n')}\n)\n\n/** Widgets whose data the server fetches (turn.uiResults[id]). */\nval UI_LIVE_NODE_TYPES = setOf(${list(UI_LIVE_NODE_TYPES)})\n\nval UI_ACTION_TYPES = setOf(${list(UI_ACTION_TYPES)})\n\n/** list item icon keys; a single emoji is accepted as well. */\nval UI_ICON_NAMES = setOf(${list(UI_ICON_NAMES)})\n\nval UI_WEATHER_ICONS = setOf(${list(UI_WEATHER_ICONS)})\n`;
// The custom-tile sandbox runtime is one file for both clients.
const runtimeSource = new URL('../packages/frontend/public/ui-widget.html', import.meta.url);
const runtimeAsset = new URL(
  '../packages/android/app/src/main/assets/dynamic-ui/ui-widget.html',
  import.meta.url
);
const runtime = readFileSync(runtimeSource, 'utf8');
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== content)
    throw new Error(
      'Android Dynamic UI catalog is stale; run node scripts/generate-dynamic-ui-catalog.mjs'
    );
  if (!existsSync(runtimeAsset) || readFileSync(runtimeAsset, 'utf8') !== runtime)
    throw new Error(
      'Android tile runtime is stale; run node scripts/generate-dynamic-ui-catalog.mjs'
    );
} else {
  writeFileSync(file, content);
  mkdirSync(new URL('.', runtimeAsset), { recursive: true });
  writeFileSync(runtimeAsset, runtime);
}
